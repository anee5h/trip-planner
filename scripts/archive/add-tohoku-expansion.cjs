function run() {
  const index = JSON.parse(fs.readFileSync(INDEX_PATH, 'utf8'));
  const meta  = JSON.parse(fs.readFileSync(META_PATH,  'utf8'));

  const existingIds = new Set(index.map(d => d.id));

  let added = 0;
  let skipped = 0;

  for (const dest of NEW_DESTINATIONS) {
    if (existingIds.has(dest.id)) {
      console.log(`  SKIP  ${dest.id} (already present)`);
      skipped++;
      continue;
    }
    // Remove helper-only typo field if any
    if (dest.budditMin !== undefined) delete dest.budditMin;
    index.push(dest);
    meta.push(toMeta(dest));
    console.log(`  ADD   ${dest.id}`);
    added++;
  }

  // Sort both arrays alphabetically by id
  index.sort((a, b) => a.id.localeCompare(b.id));
  meta.sort((a, b) => a.id.localeCompare(b.id));

  fs.writeFileSync(INDEX_PATH, JSON.stringify(index, null, 2), 'utf8');
  fs.writeFileSync(META_PATH,  JSON.stringify(meta,  null, 2), 'utf8');

  console.log(`\nDone. Added: ${added}, Skipped: ${skipped}`);
  console.log(`destinations-index.json: ${index.length} entries`);
  console.log(`destinations-meta.json:  ${meta.length} entries`);
}

run();
